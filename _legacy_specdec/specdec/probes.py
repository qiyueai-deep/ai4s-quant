"""Distribution probes on the trained target and draft checkpoints.

Prefixes are generated by the target model itself, so every probed context is
in-distribution and uses only tokens present in the shared vocabulary. No
external corpus or network access is required.
"""
from __future__ import annotations

import time

import numpy as np
import torch

from .theory import acceptance_from_tv, acceptance_monte_carlo, kl_divergence, tv_distance


def _probs(logits, temperature):
    """Float64 and explicitly normalised, so sum(min(p,q)) = 1 - TV to machine precision."""
    z = torch.softmax(logits.double() / temperature, dim=-1).numpy()
    return z / z.sum()


@torch.inference_mode()
def probe_distributions(target, draft, tokenizer, n_prompts=6, positions=32,
                        temperature=1.0, seed=0, prefix_mode="sample",
                        mc_samples=20000):
    """Collect per-position (p, q) pairs from real target and draft logits.

    'sample' draws the next context token from the target distribution, which
    is unbiased for the decoding distribution. 'greedy' is fully reproducible
    but biased upward because p and q become peaked and aligned. The main
    experiment averages over several 'sample' seeds.
    """
    rng = np.random.default_rng(seed)
    special = {"<pad>", "<bos>", "<eos>", "<unk>"}
    chars = [t for t in tokenizer.tokens if t not in special and len(t) == 1]
    starts = [tokenizer.token_to_id[c] for c in chars[:n_prompts]]
    if not starts:
        starts = [tokenizer.bos_id]
    rows = []
    for pi, start in enumerate(starts):
        cache_t, cache_d = target.new_cache(), draft.new_cache()
        x = torch.tensor([[start]], dtype=torch.long)
        logits_t = target(x, cache=cache_t)[0, -1]
        logits_d = draft(x, cache=cache_d)[0, -1]
        for step in range(positions):
            p = _probs(logits_t, temperature)
            q = _probs(logits_d, temperature)
            tok = int(p.argmax()) if prefix_mode == "greedy" else int(rng.choice(len(p), p=p / p.sum()))
            mc = acceptance_monte_carlo(p, q, rng, n=mc_samples) if mc_samples else float("nan")
            rows.append(dict(prompt=pi, step=step,
                             tv=tv_distance(p, q), alpha=acceptance_from_tv(p, q),
                             alpha_exact=float(np.minimum(p, q).sum()),
                             kl_pq=kl_divergence(p, q), kl_qp=kl_divergence(q, p),
                             top1_agree=int(p.argmax() == q.argmax()),
                             alpha_mc=mc, p=p, q=q))
            nxt = torch.tensor([[tok]], dtype=torch.long)
            logits_t = target(nxt, cache=cache_t)[0, -1]
            logits_d = draft(nxt, cache=cache_d)[0, -1]
    return rows


@torch.inference_mode()
def measure_step_costs(target, draft, token_id=0, repeats=300):
    """Wall time of one autoregressive step, used for the draft/target cost ratio."""
    one = torch.tensor([[int(token_id)]], dtype=torch.long)
    for _ in range(20):
        target(one)
        draft(one)

    def timed(model):
        t0 = time.perf_counter()
        for _ in range(repeats):
            model(one)
        return (time.perf_counter() - t0) / repeats

    tt, td = timed(target), timed(draft)
    return dict(target_step_seconds=tt, draft_step_seconds=td,
                cost_ratio=float(td / max(tt, 1e-12)))
